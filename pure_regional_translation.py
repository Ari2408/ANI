    if en_val in dict_lang:
        return dict_lang[en_val]
    
    # Sentence translation using sub_lang replacements
    res = en_val
    sorted_words = sorted(sub_lang.keys(), key=lambda x: len(x), reverse=True)
    for w in sorted_words:
        target = sub_lang[w]
        res = re.sub(r'\b' + re.escape(w) + r'\b', target, res, flags=re.IGNORECASE)
    
    return res

